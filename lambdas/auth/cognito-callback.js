import { connectDB, getDBClient } from "../../db/dbClient";
import StaffModel from "../../models/staff";
// import { formatResponse } from "../helper";

const dbClient = getDBClient();

export const handler = async (event) => {
  // Only handle sign-up verification messages
  console.log({event})
  const { userAttributes, clientMetadata, codeParameter } = event.request;
  const userId = event.userName; // Cognito User ID
  console.log({userId, userAttributes, clientMetadata});
  console.log({tempPassword: codeParameter});

  const FrontEndUrl = "http://localhost:3000";

  if(event.triggerSource === "CustomMessage_SignUp") {
        const passcode = event.request.codeParameter; // Verification code generated by Cognito
        const schoolName = event.request.clientMetadata?.school; // Custom metadata sent during sign-up

    console.log({schoolName});
    const verificationLink = `https://api.podtree.ca/verifySignup?userId=${userId}&passcode=${passcode}`;

    // Customize the email message
    const emailSubject = `Welcome to ${schoolName || 'Our Service'}! Please verify your account.`;
    const emailMessage = `
        <html>
            <body>
                <h1>Welcome to ${schoolName || 'Our Service'}</h1>
                <p>Thank you for signing up! Please verify your account by clicking the link below:</p>
                <a href="${verificationLink}">Verify Your Account</a>
                <p>If you didn't request this, please ignore this email.</p>
            </body>
        </html>
    `;
    const db = await connectDB(dbClient);
    const staffModel = new StaffModel(db);
    const user = await staffModel.findOne({userId});
    console.log({user});
    if(!user){
        // const payload = {
        //     to: clientMetadata.email,
        //     subject: emailSubject, // Email subject
        //     html: emailMessage
        // }
        // await invokeFunction('arn:aws:lambda:us-east-1:765588567347:function:email-sender', payload);// 
        event.response.emailSubject = emailSubject;
        event.response.emailMessage = emailMessage;
        return event;
    }

  } else if(event.triggerSource === "CustomMessage_AdminCreateUser") {
    const tempPassword = event.request.codeParameter;
    // const school = clientMetadata.school;
    const forcePasswordChangeURL = `${FrontEndUrl}/forcePasswordChange`;
    const forcePasswordChangeLink = `${forcePasswordChangeURL}?code=${tempPassword}&userId=${userId}`;
    const message = `
      Hello,
      
      Please reset your acadmy password by clicking the link below:
      
      ${forcePasswordChangeLink}
      
      This link will expire in 24 hours.
    `;
    event.response.emailSubject = "Change your acadmy password";
    event.response.emailMessage = message;


  } else if (event.triggerSource === "CustomMessage_ForgotPassword"){

    // Get the verification code from the event
    const { codeParameter } = event.request;

    // Get your app's verification URL from environment variables
    const verificationURL = `${FrontEndUrl}/verify` // process.env.VERIFICATION_BASE_URL;
    
    // Create a verification link with the code and username
    const verificationLink = `${verificationURL}?code=${codeParameter}&userId=${userId}`;
    
    // Customize the email message ${clientMetadata.school}
    const message = `
      Hello,
      
      Thank you for signing up acadmy! Please verify your email by clicking the link below:
      
      ${verificationLink}
      
      If you didn't create this account, please ignore this email.
      
      This link will expire in 24 hours.
    `;

    // Set the custom message and subject
    event.response.emailSubject = "Verify your email address";
    event.response.emailMessage = message;
  }
  
  return event;
};
